"""One editable pixel catalog -> transparent SVG + equivalent native UI geometry."""
from pathlib import Path
import argparse
import json
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
CATALOGS = (("assets/store/catalog.json", "src/client/StoreIconCatalog.luau", "store"),
            ("assets/features/catalog.json", "src/client/FeatureIconCatalog.luau", "feature"))


def outputs(catalog_relative="assets/store/catalog.json", native_relative="src/client/StoreIconCatalog.luau"):
    catalog_path = ROOT / catalog_relative
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    records, files = {}, {}
    for entry in catalog["icons"]:
        identifier, pixels, color = entry["id"], entry["pixels"], entry["color"]
        assert re.fullmatch(r"[a-z][a-z0-9_-]{0,31}", identifier) and identifier not in records
        assert 1 <= len(pixels) <= 32 and 1 <= len(pixels[0]) <= 32
        width, height = len(pixels[0]), len(pixels)
        palette = entry.get("palette", {"#": color})
        assert all(len(symbol) == 1 and symbol != "." for symbol in palette)
        assert all(len(rgb) == 3 and all(type(v) is int and 0 <= v <= 255 for v in rgb) for rgb in palette.values())
        assert all(len(row) == width and set(row) <= {".", *palette} for row in pixels)
        assert len(color) == 3 and all(type(v) is int and 0 <= v <= 255 for v in color)
        # Merge identical horizontal runs across rows. Transparent eyes/background
        # stay genuine holes, not white paint or terminal-colored cover rectangles.
        parts, previous = [], {}
        for y, row in enumerate(pixels):
            current = {}
            for match in re.finditer(r"([^.])\1*", row):
                key = (match.start(), len(match.group()), match.group()[0])
                if key in previous:
                    index = previous[key]
                    parts[index][3] += 1
                else:
                    index = len(parts)
                    parts.append([key[0], y, key[1], 1, key[2]])
                current[key] = index
            previous = current
        assert 1 <= len(parts) <= 128
        reconstructed = [["."] * width for _ in range(height)]
        for x,y,w,h,symbol in parts:
            assert x >= 0 and y >= 0 and x+w <= width and y+h <= height
            for py in range(y,y+h):
                for px in range(x,x+w):
                    assert reconstructed[py][px] == ".", "Overlapping icon rectangles"
                    reconstructed[py][px] = symbol
        assert ["".join(row) for row in reconstructed] == pixels, "Icon geometry changed the source artwork"
        records[identifier] = (entry, width, height, parts)
        rgb = "#" + "".join(f"{v:02x}" for v in color)
        rects = "\n".join(f'    <rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#{"".join(f"{v:02x}" for v in palette[symbol])}"/>' for x,y,w,h,symbol in parts)
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="256" height="{256*height/width:g}" viewBox="0 0 {width} {height}" shape-rendering="crispEdges" role="img" aria-labelledby="title description">
  <title id="title">{escape(entry['name'])}</title>
  <desc id="description">{escape(entry['description'])}</desc>
  <g fill="{rgb}">
{rects}
  </g>
</svg>
'''
        files[catalog_path.parent / f"{identifier}.svg"] = svg
    assert catalog["default"] in records
    code = ["--!nonstrict", f"-- Generated by tools/generate_store_icons.py; edit {catalog_relative}.",
            "return {", f'    DEFAULT = {json.dumps(catalog["default"])},']
    for identifier, (entry, width, height, parts) in records.items():
        code.extend([f'    [{json.dumps(identifier)}] = {{', f'        name = {json.dumps(entry["name"])},',
                     f'        width = {width}, height = {height},',
                     '        color = {' + ', '.join(map(str, entry['color'])) + '},', '        parts = {'])
        palette=entry.get("palette", {"#": entry["color"]})
        code.extend('            {' + ', '.join(map(str, part[:4])) + ', {' + ', '.join(map(str,palette[part[4]])) + '}},' for part in parts)
        code.extend(['        },', '    },'])
    code.append('}')
    files[ROOT / native_relative] = '\n'.join(code) + '\n'
    return files


def verify_generated():
    for catalog_relative,native_relative,label in CATALOGS:
        for path, expected in outputs(catalog_relative,native_relative).items():
            assert path.exists() and path.read_text(encoding="utf-8") == expected, f"Stale icon output: {path.name}; run tools/generate_store_icons.py"
        print(f"PASS {label} icon SVG/native geometry equality (editable catalog, transparent artwork)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    if parser.parse_args().check:
        verify_generated()
    else:
        for catalog_relative,native_relative,_ in CATALOGS:
            for path, content in outputs(catalog_relative,native_relative).items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
                print(f"Generated {path.relative_to(ROOT)}")
