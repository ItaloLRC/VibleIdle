"""Compile the user's SVG animation into offline native Roblox pixel geometry."""
from pathlib import Path
import argparse
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/skill-fire"
PALETTE = ["#702839", "#E9472B", "#FF862C", "#FFD34D", "#FFF2AC"]


def animation():
    source = json.loads((ASSETS / "source.json").read_text(encoding="utf-8"))
    manifest = json.loads((ASSETS / "manifesto.json").read_text(encoding="utf-8"))
    assert manifest["total_frames"] == 36 and manifest["frames_por_bola"] == 12
    assert manifest["duracao_frame_ms"] == 100
    tiers, capacity = [], 0
    for index, folder in enumerate(source["folders"]):
        height = 80 if index == 2 else 64
        center = [32.5, 62.5 if index == 2 else 46.5]
        frames = []
        for frame in range(1, 13):
            svg = ET.fromstring((ASSETS / folder / f"frame-{frame:02d}.svg").read_bytes())
            assert svg.attrib["viewBox"] == f"0 0 64 {height}"
            parts, blacks, pixels = [], [], {}
            for node in svg:
                tag = node.tag.rsplit("}", 1)[-1]
                if tag == "title":
                    continue
                assert tag == "rect", "Only offline pixel rectangle data is supported"
                x, y, w, h = [int(node.attrib[key]) for key in ("x", "y", "width", "height")]
                color = node.attrib["fill"].upper()
                assert x >= 0 and y >= 0 and w > 0 and h > 0 and x+w <= 64 and y+h <= height
                assert color == "#000000" or color in PALETTE
                for py in range(y, y+h):
                    for px in range(x, x+w):
                        assert (px, py) not in pixels, "Overlapping source rectangles"
                        pixels[px, py] = color
                if color == "#000000":
                    blacks.append((x, y, w, h))
                else:
                    parts.append([x, y, w, h, PALETTE.index(color)+1])
            # Circle stays supplied artwork data; the existing button covers it.
            bounds = [min(r[0] for r in blacks), min(r[1] for r in blacks),
                      max(r[0]+r[2] for r in blacks), max(r[1]+r[3] for r in blacks)]
            assert bounds == [19, center[1]-13.5, 46, center[1]+13.5]
            assert 0 < len(parts) <= 256
            capacity = max(capacity, len(parts))
            frames.append(parts)
        tiers.append(dict(center=center, height=height, frames=frames))
    assert len(tiers) == 3
    return tiers, capacity


def output():
    tiers, capacity = animation()
    lines = ["--!nonstrict", "-- Generated by tools/generate_skill_fire.py from user-supplied SVG frames.",
             "return {", f"    CAPACITY = {capacity}, FPS = 10, FRAME_COUNT = 12, CIRCLE_DIAMETER = 27,",
             "    colors = {"]
    for color in PALETTE:
        rgb = [str(int(color[i:i+2], 16)) for i in (1, 3, 5)]
        lines.append("        {" + ",".join(rgb) + "},")
    lines.extend(["    },", "    tiers = {"])
    for tier in tiers:
        lines.extend(["        {", f"            centerX = {tier['center'][0]}, centerY = {tier['center'][1]},",
                      "            frames = {"])
        for parts in tier["frames"]:
            lines.append("                {" + ",".join("{" + ",".join(map(str, p)) + "}" for p in parts) + "},")
        lines.extend(["            },", "        },"])
    lines.extend(["    },", "}"])
    return "\n".join(lines) + "\n"


def verify_generated():
    target = ROOT / "src/client/SkillFireCatalog.luau"
    assert target.read_text(encoding="utf-8") == output(), "Stale fire catalog; run tools/generate_skill_fire.py"
    print("PASS supplied fire SVG/native geometry equality (36 frames, aligned circle, bounded pool)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    if parser.parse_args().check:
        verify_generated()
    else:
        (ROOT / "src/client/SkillFireCatalog.luau").write_text(output(), encoding="utf-8")
        print("Generated src/client/SkillFireCatalog.luau")
